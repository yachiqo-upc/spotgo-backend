package com.yachiqo.spotgo.profiles.interfaces.rest.resources;
import com.yachiqo.spotgo.profiles.domain.model.aggregates.Profile;
import java.time.Instant;
import java.util.UUID;
import io.swagger.v3.oas.annotations.media.Schema;
public record ProfileResource(
    @Schema(description = "Profile UUID (profiles.profile_id). It differs from the account ID.", example = "00000000-0000-4000-8000-000000000012") UUID id,
    @Schema(description = "UUID of the IAM account linked to this profile.", example = "00000000-0000-4000-8000-000000000002") UUID accountId,
    @Schema(description = "Nombres.", example = "Juan") String firstName,
    @Schema(description = "Apellidos.", example = "Demo") String lastName,
    @Schema(description = "Contact phone number.", example = "900000002") String phone,
    @Schema(description = "UTC timestamp when this row was created, generated by the backend.", example = "2026-11-09T07:00:00Z") Instant createdAt,
    @Schema(description = "UTC timestamp of the last update to this row.", example = "2026-11-09T07:00:00Z") Instant updatedAt) {
    public static ProfileResource from(Profile p) {
        return new ProfileResource(p.getId(), p.getAccountId(), p.getFirstName(), p.getLastName(),
            p.getPhone(), p.getCreatedAt(), p.getUpdatedAt());
    }
}
